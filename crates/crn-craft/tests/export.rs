//! The GillesPy2 reference export on the flat view (M5f): network models
//! (through the converter) keep their 0.6.0 source where 0.6.0 exported
//! them; rules models and `crn-craft.model/1.0` export with their species
//! labels; a channel without a constant rate of order at most two exports
//! as a custom propensity string.
use crn_craft::export::export_gillespy2;
use serde_json::{Value, json};

fn model(names: &[&str], counts: &[i64], columns: &[Vec<i64>]) -> Value {
    let reactions: Vec<_> = columns.iter().enumerate().map(|(r, col)| {
        let mut left = serde_json::Map::new(); let mut right = serde_json::Map::new();
        for (name, c) in names.iter().zip(col) {
            if *c < 0 { left.insert((*name).into(), json!(-c)); }
            if *c > 0 { right.insert((*name).into(), json!(c)); }
        }
        json!({"name":format!("r{r}"),"reactants":left,"products":right,"rate":{"kind":"mass_action","coefficient":1.0}})
    }).collect();
    json!({"schema":"crn-craft.model/0.1","name":"structure","convention":"stochastic_counts","omega":1.0,"parameters":{},
        "species":names.iter().zip(counts).map(|(name,count)|json!({"name":name,"initial_count":count})).collect::<Vec<_>>(),"reactions":reactions})
}
fn bytes(value: &Value) -> Vec<u8> {
    serde_json::to_vec(value).unwrap()
}

/// The source lines that add reactions.
fn reactions(source: &str) -> Vec<&str> {
    source
        .lines()
        .filter(|line| line.contains("model.add_reaction"))
        .collect()
}

/// The custom propensity string of each reaction line, if any.
fn propensities(source: &str) -> Vec<String> {
    reactions(source)
        .iter()
        .filter_map(|line| {
            let (_, rest) = line.split_once("propensity_function=")?;
            let text: String = serde_json::from_str(rest.trim_end_matches("))")).ok()?;
            Some(text)
        })
        .collect()
}

fn refusal(model: &Value) -> (String, String) {
    let report = export_gillespy2(&bytes(model));
    assert!(!report.success, "{model}");
    assert!(report.artifact.is_none());
    let first = &report.diagnostics[0];
    (first.code.clone(), first.path.clone())
}

#[test]
fn export_halves_homodimer_and_uses_safe_aliases_unit_volume() {
    let mut value = model(&["vol", "K0"], &[3, 0], &[vec![-2, 1]]);
    value["omega"] = json!(1000);
    let report = export_gillespy2(&bytes(&value));
    assert!(report.success);
    assert_eq!(report.model_sha256, Some(crn_craft::sha256(&bytes(&value))));
    let artifact = report.artifact.unwrap();
    assert_eq!(artifact.target_version, "1.8.3");
    assert!(artifact.source.contains("expression=0.5"));
    assert!(artifact.source.contains("volume=1.0"));
    assert_eq!(artifact.species_aliases["vol"], "S0");
    assert_eq!(artifact.species_aliases["K0"], "S1");
}

#[test]
fn network_models_keep_their_0_6_0_artifact() {
    // The 0.6.0 export of this model, as `crn-craft export` printed it.
    let model = br#"{"schema": "crn-craft.model/0.1", "name": "decay", "convention": "stochastic_counts", "omega": 1.0, "parameters": {"k": 0.1}, "species": [{"name": "A", "initial_count": 10}, {"name": "B", "initial_count": 0}], "reactions": [{"name": "death", "reactants": {"A": 1}, "products": {}, "rate": {"kind": "mass_action", "coefficient": "k"}}, {"name": "pair", "reactants": {"A": 2}, "products": {"B": 1}, "rate": {"kind": "mass_action", "coefficient": 0.5}}, {"name": "bind", "reactants": {"B": 1, "A": 1}, "products": {"A": 2}, "rate": {"kind": "mass_action", "coefficient": 1e-7}}, {"name": "make", "reactants": {}, "products": {"B": 1, "A": 1}, "rate": {"kind": "mass_action", "coefficient": 3.0}}]}
"#;
    let source = "# Generated by CRN-craft. Stochastic-count semantics; reference SSA only.
# Model SHA-256: a6e508e01df9372469933dea4b71d10d39405bf6d36972b6102a680316176470
import gillespy2 as gp

def build_model():
    if gp.__version__ != \"1.8.3\":
        raise RuntimeError('Requires GillesPy2 1.8.3')
    model = gp.Model(name=\"decay\", population=True, volume=1.0)
    species = [
        gp.Species(name='S0', initial_value=10, mode='discrete'),
        gp.Species(name='S1', initial_value=0, mode='discrete'),
    ]
    model.add_species(species)
    rate = gp.Parameter(name='K0', expression=0.1)
    model.add_parameter(rate)
    model.add_reaction(gp.Reaction(name='R0', reactants={species[0]: 1}, products={}, rate=rate))
    rate = gp.Parameter(name='K1', expression=0.25)
    model.add_parameter(rate)
    model.add_reaction(gp.Reaction(name='R1', reactants={species[0]: 2}, products={species[1]: 1}, rate=rate))
    rate = gp.Parameter(name='K2', expression=1e-7)
    model.add_parameter(rate)
    model.add_reaction(gp.Reaction(name='R2', reactants={species[0]: 1, species[1]: 1}, products={species[0]: 2}, rate=rate))
    rate = gp.Parameter(name='K3', expression=3.0)
    model.add_parameter(rate)
    model.add_reaction(gp.Reaction(name='R3', reactants={}, products={species[0]: 1, species[1]: 1}, rate=rate))
    return model
";
    let report = export_gillespy2(model);
    assert!(report.success, "{:?}", report.diagnostics);
    assert!(report.diagnostics.is_empty());
    let artifact = report.artifact.unwrap();
    assert_eq!(artifact.source, source);
    assert_eq!(
        serde_json::to_value(&artifact.reaction_aliases).unwrap(),
        json!({"bind": "R2", "death": "R0", "make": "R3", "pair": "R1"})
    );
    assert_eq!(artifact.notes.len(), 4);
    // The converted model exports the same artifact; only the hash line differs.
    let converted = crn_craft::rules::convert::from_network(model).unwrap();
    let other = export_gillespy2(&converted).artifact.unwrap();
    assert_eq!(
        other.source.replace(&crn_craft::sha256(&converted), "HASH"),
        source.replace(&crn_craft::sha256(model), "HASH")
    );
    assert_eq!(other.species_aliases, artifact.species_aliases);
}

#[test]
fn rate_laws_without_a_constant_rate_export_custom_propensities() {
    let network = |reactants: Value, rate: Value| {
        bytes(&json!({
            "schema": "crn-craft.model/0.1", "name": "law", "convention": "stochastic_counts",
            "omega": 1.0, "parameters": {"vmax": 5.0, "km": 20.0, "c": 0.25},
            "species": [{"name": "S", "initial_count": 50}, {"name": "P", "initial_count": 0}],
            "reactions": [{"name": "r", "reactants": reactants, "products": {"P": 1}, "rate": rate}]
        }))
    };
    let custom = |model: &[u8]| {
        let report = export_gillespy2(model);
        assert!(report.success, "{:?}", report.diagnostics);
        let artifact = report.artifact.unwrap();
        assert_eq!(artifact.notes.len(), 5);
        assert!(!artifact.source.contains("gp.Parameter"));
        propensities(&artifact.source)
    };
    // Michaelis-Menten: the converted expression, gated by S >= 1.
    assert_eq!(
        custom(&network(
            json!({"S": 1}),
            json!({"kind": "michaelis_menten", "substrate": "S", "vmax": "vmax", "km": "km"})
        )),
        ["(5.0 * (S0 / (20.0 + S0))) * (S0/(S0 + 1e-300))"]
    );
    // Hill repression without reactants: no gate.
    assert_eq!(
        custom(&network(
            json!({}),
            json!({"kind": "hill_repression", "regulator": "S", "vmax": 2.0, "basal": 0.5, "k": "km", "n": 2})
        )),
        ["(0.5 + (2.0 / (1.0 + ((S0 / 20.0) ** 2.0))))"]
    );
    // Mass action of order three: the falling factorial over 3!.
    assert_eq!(
        custom(&network(
            json!({"S": 3}),
            json!({"kind": "mass_action", "coefficient": "c"})
        )),
        ["0.25 * ((S0 * (S0 - 1.0) * (S0 - 2.0)) / 6.0)"]
    );
}

/// Two copies of `M` that switch between `wt = 0` and `wt = 1`, lost at a
/// rate that grows with the mutant count.
fn switching() -> Value {
    json!({
        "schema": "crn-craft.model/1.0", "name": "switching",
        "parameters": {"k": 0.5, "r": 0.25},
        "types": [{"name": "M", "attributes": ["wt"]}, {"name": "E"}],
        "initial": [
            {"type": "M", "attributes": {"wt": 0}, "count": 10},
            {"type": "M", "attributes": {"wt": 1}, "count": 2}
        ],
        "observables": {
            "mutants": {"type": "M", "where": "x.wt == 1"},
            "load": {"type": "M", "weight": "1 + x.wt"}
        },
        "rules": [
            {"name": "mutate", "reactants": [{"label": "x", "type": "M", "where": "x.wt == 0", "factor": "2"}],
             "rate": "k", "products": [{"type": "M", "attributes": {"wt": 1}}, {"type": "E"}]},
            {"name": "loss", "reactants": [{"label": "x", "type": "M"}],
             "rate": "r * load", "products": []},
            {"name": "clear", "reactants": [{"label": "x", "type": "E", "count": 2}],
             "propensity": "k * mutants", "products": []}
        ]
    })
}

#[test]
fn rules_models_export_with_flat_labels_and_channel_names() {
    let report = export_gillespy2(&bytes(&switching()));
    assert!(report.success, "{:?}", report.diagnostics);
    let artifact = report.artifact.unwrap();
    assert_eq!(
        serde_json::to_value(&artifact.species_aliases).unwrap(),
        json!({"E": "S2", "M{wt=0}": "S0", "M{wt=1}": "S1"})
    );
    assert_eq!(
        serde_json::to_value(&artifact.reaction_aliases).unwrap(),
        json!({"clear": "R3", "loss[0]": "R1", "loss[1]": "R2", "mutate": "R0"})
    );
    let lines = reactions(&artifact.source);
    assert_eq!(lines.len(), 4);
    // The constant rate times the pattern factor is mass action.
    assert!(
        artifact
            .source
            .contains("rate = gp.Parameter(name='K0', expression=1.0)")
    );
    assert!(
        lines[0].contains(
            "reactants={species[0]: 1}, products={species[2]: 1, species[1]: 1}, rate=rate"
        )
    );
    assert_eq!(
        propensities(&artifact.source),
        [
            "(0.25 * (S0 + 2.0 * S1)) * S0",
            "(0.25 * (S0 + 2.0 * S1)) * S1",
            "(0.5 * S1) * (S2/(S2 + 1e-300)) * ((S2 - 1.0)/((S2 - 1.0) + 1e-300))"
        ]
    );
}

#[test]
fn what_gillespy2_cannot_evaluate_is_refused_with_e050() {
    let with = |path: &str, value: Value| {
        let mut model = switching();
        let mut target = &mut model;
        for key in path.split('/') {
            target = match key.parse::<usize>() {
                Ok(i) => &mut target[i],
                Err(_) => &mut target[key],
            };
        }
        *target = value;
        model
    };
    for (rate, construct) in [
        ("r * exp(load)", "`exp`"),
        ("max(r, load)", "`max`"),
        ("if(load > 3, r, 0)", "`if`"),
        ("r * (load >= 3)", "`>=`"),
    ] {
        let model = with("rules/1/rate", json!(rate));
        assert_eq!(
            refusal(&model),
            ("CRN-E050".into(), "/rules/1/rate".into()),
            "{rate}"
        );
        let report = export_gillespy2(&bytes(&model));
        assert!(
            report.diagnostics[0].message.contains(construct),
            "{}",
            report.diagnostics[0].message
        );
    }
    let distinct = with(
        "observables/load",
        json!({"type": "M", "reduce": "distinct"}),
    );
    assert_eq!(
        refusal(&distinct),
        ("CRN-E050".into(), "/rules/1/rate".into())
    );
    let mut stopped = switching();
    stopped["stop"] = json!("mutants >= 5");
    assert_eq!(refusal(&stopped), ("CRN-E050".into(), "/stop".into()));
    let negative = with("parameters/k", json!(-0.5));
    assert_eq!(
        refusal(&negative),
        ("CRN-E050".into(), "/rules/0/rate".into())
    );
    let many = with("rules/2/reactants/0/count", json!(65));
    assert_eq!(
        refusal(&many),
        ("CRN-E050".into(), "/rules/2/reactants".into())
    );
    // 64 molecules are written out.
    assert!(export_gillespy2(&bytes(&with("rules/2/reactants/0/count", json!(64)))).success);
}

#[test]
fn models_without_an_export_are_refused_before_emitting_code() {
    let base = model(&["A"], &[2], &[vec![-1]]);
    // The converter refuses what a rules model cannot hold.
    for (mutate, code) in [
        (
            (|v: &mut Value| v["species"][0]["population_limit"] = json!(10)) as fn(&mut Value),
            "CRN-R016",
        ),
        (
            |v: &mut Value| v["species"][0]["initial_count"] = json!(9_007_199_254_740_993_i64),
            "CRN-R016",
        ),
        (|v: &mut Value| v["reactions"] = json!([]), "CRN-R016"),
        (
            |v: &mut Value| v["reactions"][0]["products"]["B"] = json!(1),
            "CRN-E012",
        ),
    ] {
        let mut value = base.clone();
        mutate(&mut value);
        let report = export_gillespy2(&bytes(&value));
        assert!(!report.success);
        assert!(report.artifact.is_none());
        assert_eq!(report.diagnostics[0].code, code, "{value}");
    }
    // Order three and Michaelis-Menten, refused by 0.6.0, export.
    for mutate in [
        (|v: &mut Value| v["reactions"][0]["reactants"]["A"] = json!(3)) as fn(&mut Value),
        |v: &mut Value| {
            v["reactions"][0]["rate"] =
                json!({"kind":"michaelis_menten","substrate":"A","vmax":1,"km":1})
        },
    ] {
        let mut value = base.clone();
        mutate(&mut value);
        assert!(export_gillespy2(&bytes(&value)).success, "{value}");
    }
    // A model without a flat view.
    let mut growing = switching();
    growing["rules"][0]["products"][0] =
        json!({"type": "M", "copy": "x", "attributes": {"wt": "x.wt + 2"}});
    assert_eq!(refusal(&growing), ("CRN-R017".into(), "/rules".into()));
}

#[test]
fn export_rejects_inexact_subnormal_halving_but_accepts_exact_boundary() {
    let mut value = model(&["A"], &[2], &[vec![-2]]);
    for bits in [1, 2, 3, 4] {
        value["reactions"][0]["rate"]["coefficient"] = json!(f64::from_bits(bits));
        let report = export_gillespy2(&bytes(&value));
        assert_eq!(report.success, bits % 2 == 0);
        if bits % 2 != 0 {
            assert_eq!(report.diagnostics[0].code, "CRN-E051");
            assert_eq!(report.diagnostics[0].path, "/rules/0/rate");
            assert!(report.artifact.is_none());
        }
    }
}

#[test]
fn export_validates_typed_contract_and_exact_float_count_boundary() {
    let mut value = model(&["A"], &[9_007_199_254_740_992], &[vec![-1]]);
    assert!(export_gillespy2(&bytes(&value)).success);
    value["unexpected"] = json!(true);
    assert_eq!(
        export_gillespy2(&bytes(&value)).diagnostics[0].code,
        "CRN-E003"
    );
    assert!(!export_gillespy2(b"{}").success);
}
